export type ErDemoSlug = (typeof ER_DEMO_NICHES)[number]['slug'];
export type ErDemoNiche = (typeof ER_DEMO_NICHES)[number];

export const DEFAULT_ER_DEMO_SLUG: ErDemoSlug = 'hvac';

export function getErDemoNiche(slug?: string | null): ErDemoNiche | undefined {
  if (!slug) return undefined;
  const normalized = slug.trim().toLowerCase();
  const aliases: Record<string, ErDemoSlug> = {
    auto: 'auto-repair',
    automotive: 'auto-repair',
    electric: 'electrical',
    electrician: 'electrical',
    plumber: 'plumbing',
    roofer: 'roofing',
    'heating-and-air': 'hvac',
    hvactech: 'hvac',
  };
  const mapped = aliases[normalized] ?? (normalized as ErDemoSlug);
  return ER_DEMO_NICHES.find((niche) => niche.slug === mapped);
}

export function isErDemoSlug(slug: string): slug is ErDemoSlug {
  return ER_DEMO_NICHES.some((niche) => niche.slug === slug);
}
